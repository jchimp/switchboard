using System.Collections.ObjectModel;
using System.ComponentModel;
using System.Diagnostics;
using System.Windows.Media;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using Switchboard.App.Services;
using Switchboard.Core.Registry;
using Switchboard.Core.Status;
using Switchboard.Core.WindowsTerminal;

namespace Switchboard.App.ViewModels;

/// <summary>
/// The right-hand editor on the Terminals page. Unlike the settings pages this commits on an
/// explicit Save (ADR-0018): a name change rebinds a live window (ADR-0014), which is not
/// something to do on every keystroke.
/// </summary>
public sealed partial class TerminalEditorViewModel : ObservableObject
{
    private readonly TerminalSession _session;
    private readonly TerminalDefinition _original;
    private WtProfileCatalog _profiles;

    // The user's own shell and distro. What the editor shows is derived from these plus the
    // current profile, never accumulated, so auto-complete passing through a profile name
    // can't leave a changed shell behind (WtProfileReader.Resolve).
    private ShellKind _userShell;
    private string _userDistro;
    private bool _resolving;

    /// <summary>Null for a row being added; otherwise the name to update, before any rename.</summary>
    private readonly string? _editingName;

    public TerminalEditorViewModel(
        TerminalSession session, TerminalDefinition definition, bool isNew, WtProfileCatalog profiles)
    {
        _session = session;
        _original = definition;
        _profiles = profiles;
        _editingName = isNew ? null : definition.Name;
        IsNew = isNew;

        _name = definition.Name;
        _tag = definition.Tag;
        _color = definition.Color;
        _profile = definition.Profile;
        _shell = definition.Shell;
        _distro = definition.Distro ?? string.Empty;
        _userShell = _shell;
        _userDistro = _distro;
        _workingDirectory = definition.WorkingDirectory ?? string.Empty;
        _command = definition.Command ?? string.Empty;
        _jumpKey = definition.JumpKey;
        _lockTitle = definition.LockTitle;
        _persistent = definition.Persistent;

        foreach (var rule in definition.StatusRules)
        {
            Rules.Add(new StatusRuleRowViewModel(rule));
        }

        OnColorChanged(_color);
    }

    public bool IsNew { get; }

    /// <summary>The nine product hues, with the current one ringed.</summary>
    public IReadOnlyList<ColorSwatchViewModel> Palette { get; } =
        ColorPalette.Hues.Select(h => new ColorSwatchViewModel(h)).ToList();

    public static IReadOnlyList<ShellKind> Shells { get; } =
        [ShellKind.Pwsh, ShellKind.WindowsPowerShell, ShellKind.Cmd, ShellKind.Wsl];

    public ObservableCollection<StatusRuleRowViewModel> Rules { get; } = [];

    /// <summary>The terminal host's profiles (or the installed WT's when no host is set).</summary>
    public IReadOnlyList<string> ProfileNames => _profiles.VisibleNames;

    /// <summary>The selected profile as WT sees it; null when the name matches none.</summary>
    public WtProfileDetail? ProfileDetail => _profiles.Find(Profile);

    public bool HasProfileDetail => ProfileDetail is not null;

    /// <summary>
    /// A name WT does not know: it would silently open its default profile instead. Only said
    /// when there is a list to check against.
    /// </summary>
    public bool ProfileNotFound =>
        _profiles.Profiles.Count > 0 && ProfileDetail is null && !string.IsNullOrWhiteSpace(Profile);

    public string ProfileCommandline => ProfileDetail?.Commandline ?? "(generated by Windows Terminal)";

    public string ProfileStartingDirectory => ProfileDetail?.StartingDirectory ?? "(profile default)";

    public string ProfileFont => ProfileDetail switch
    {
        { FontFace: { } face, FontSize: { } size } => $"{face}, {size} pt",
        { FontFace: { } face } => face,
        { FontSize: { } size } => $"default face, {size} pt",
        _ => "(Windows Terminal default)",
    };

    public string ProfileColorScheme => ProfileDetail?.ColorScheme ?? "(Windows Terminal default)";

    public string? SettingsFilePath => _profiles.SettingsPath;

    /// <summary>Raised after a successful save so the page can re-select the (possibly renamed) row.</summary>
    public event Action<string>? Saved;

    [ObservableProperty]
    private string _name;

    [ObservableProperty]
    private string _tag;

    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(Swatch))]
    private string _color;

    [ObservableProperty]
    private string _profile;

    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(IsWsl))]
    private ShellKind _shell;

    [ObservableProperty]
    private string _distro;

    [ObservableProperty]
    private string _workingDirectory;

    [ObservableProperty]
    private string _command;

    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(JumpKeyText))]
    private int? _jumpKey;

    [ObservableProperty]
    private bool _lockTitle;

    [ObservableProperty]
    private bool _persistent;

    [ObservableProperty]
    [NotifyPropertyChangedFor(nameof(HasError))]
    private string? _error;

    public bool HasError => Error is not null;

    public bool IsWsl => Shell == ShellKind.Wsl;

    public SolidColorBrush Swatch => Freeze(Color);

    /// <summary>The wt window name is the terminal name, always (invariant 4). Shown read-only.</summary>
    public string WindowName => Name;

    partial void OnNameChanged(string value) => OnPropertyChanged(nameof(WindowName));

    /// <summary>
    /// Picking a profile brings its shell (and a WSL profile its distro) with it, so the two can
    /// no longer disagree by accident; both stay editable for a profile Switchboard can't read.
    /// Not run for the saved values the editor opens with.
    /// </summary>
    partial void OnProfileChanged(string value)
    {
        RaiseProfileDetails();

        var (shell, distro) = WtProfileReader.Resolve(ProfileDetail, _userShell, Blank(_userDistro));
        _resolving = true;
        try
        {
            Shell = shell;
            Distro = distro ?? string.Empty;
        }
        finally
        {
            _resolving = false;
        }
    }

    // A hand-made choice becomes the new baseline; values set by Resolve do not.
    partial void OnShellChanged(ShellKind value)
    {
        if (!_resolving)
        {
            _userShell = value;
        }
    }

    partial void OnDistroChanged(string value)
    {
        if (!_resolving)
        {
            _userDistro = value;
        }
    }

    /// <summary>
    /// Swaps in a freshly read profile list (Settings reopened, host folder changed) without
    /// touching Shell or Distro: nothing the user did changed.
    /// </summary>
    public void UseProfiles(WtProfileCatalog profiles)
    {
        _profiles = profiles;
        OnPropertyChanged(nameof(ProfileNames));
        OnPropertyChanged(nameof(SettingsFilePath));
        OpenSettingsFileCommand.NotifyCanExecuteChanged();
        RaiseProfileDetails();
    }

    private void RaiseProfileDetails()
    {
        OnPropertyChanged(nameof(ProfileDetail));
        OnPropertyChanged(nameof(HasProfileDetail));
        OnPropertyChanged(nameof(ProfileNotFound));
        OnPropertyChanged(nameof(ProfileCommandline));
        OnPropertyChanged(nameof(ProfileStartingDirectory));
        OnPropertyChanged(nameof(ProfileFont));
        OnPropertyChanged(nameof(ProfileColorScheme));
    }

    /// <summary>Opens WT's settings.json in the user's editor, for anything the panel doesn't show.</summary>
    [RelayCommand(CanExecute = nameof(CanOpenSettingsFile))]
    private void OpenSettingsFile()
    {
        try
        {
            // CanExecute guarantees a path.
            using var _ = Process.Start(new ProcessStartInfo(SettingsFilePath!) { UseShellExecute = true });
        }
        catch (Exception ex) when (ex is Win32Exception or InvalidOperationException)
        {
            Error = $"Could not open {SettingsFilePath}: {ex.Message}";
        }
    }

    private bool CanOpenSettingsFile() => SettingsFilePath is not null;

    partial void OnColorChanged(string value)
    {
        foreach (var swatch in Palette)
        {
            swatch.IsSelected = string.Equals(swatch.Hex, value, StringComparison.OrdinalIgnoreCase);
        }
    }

    /// <summary>
    /// Jump key as text so the box can be emptied. Anything that is not 1–9 clears the key
    /// rather than erroring: Validate() would reject it on Save, which is a poor way to
    /// learn that a stray character is not a jump key.
    /// </summary>
    public string JumpKeyText
    {
        get => JumpKey?.ToString() ?? string.Empty;
        set => JumpKey = int.TryParse(value, out var digit) && digit is >= 1 and <= 9 ? digit : null;
    }

    [RelayCommand]
    private void SelectColor(ColorSwatchViewModel swatch) => Color = swatch.Hex;

    [RelayCommand]
    private void AddRule() => Rules.Add(new StatusRuleRowViewModel(
        new StatusRule { State = TerminalState.Working, Pattern = string.Empty }));

    [RelayCommand]
    private void RemoveRule(StatusRuleRowViewModel rule) => Rules.Remove(rule);

    [RelayCommand]
    private async Task Save()
    {
        Error = null;

        if (Rules.FirstOrDefault(r => r.HasError) is { } bad)
        {
            Error = $"Rule '{bad.Pattern}': {bad.Error}";
            return;
        }

        var updated = Build();
        try
        {
            if (_editingName is { } existing)
            {
                await _session.UpdateTerminalAsync(existing, updated);
            }
            else
            {
                await _session.AddTerminalAsync(updated);
            }

            Saved?.Invoke(updated.Name);
        }
        catch (ArgumentException ex)
        {
            // Validate() and the duplicate-name check both arrive here; show them inline.
            Error = ex.Message;
        }
    }

    [RelayCommand]
    private Task Launch() => _session.ActivateAsync(_original.Name);

    private TerminalDefinition Build() => _original with
    {
        Name = Name.Trim(),
        Tag = Tag.Trim(),
        Color = Color,
        Profile = Profile.Trim(),
        Shell = Shell,
        Distro = Blank(Distro),
        WorkingDirectory = Blank(WorkingDirectory),
        Command = Blank(Command),
        JumpKey = JumpKey,
        LockTitle = LockTitle,
        Persistent = Persistent,
        StatusRules = Rules.Select(r => r.ToRule()).ToList(),
    };

    private static string? Blank(string value) => string.IsNullOrWhiteSpace(value) ? null : value.Trim();

    private static SolidColorBrush Freeze(string hex)
    {
        var brush = (SolidColorBrush)new BrushConverter().ConvertFromString(hex)!;
        brush.Freeze();
        return brush;
    }
}
